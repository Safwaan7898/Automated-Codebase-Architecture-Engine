/**
 * AILabel – reusable "AI-generated" badge used on every AI-annotated piece
 * of content.  Must appear next to every AI text output per the hard invariant.
 *
 * RULE: AI text must ALWAYS show this label and must ALWAYS have a deterministic
 * fallback.  This component enforces both visually.
 */
import { Sparkles } from 'lucide-react'
import type { ReactNode } from 'react'

interface AILabelProps {
  /** Label text. Defaults to 'AI-generated'. */
  label?: string
  /** Provide children to render a labelled block (badge + content). */
  children?: ReactNode
  /** Size variant.  Default "sm". */
  size?: 'xs' | 'sm'
  className?: string
}

/**
 * Inline badge – use stand-alone next to a heading/card title.
 */
export function AIBadge({ label = 'AI-generated', size = 'sm', className = '' }: AILabelProps) {
  const px = size === 'xs' ? 'px-1.5 py-0.5 text-[9px]' : 'px-2 py-0.5 text-[10px]'
  return (
    <span
      className={`inline-flex items-center gap-1 rounded-full font-bold uppercase tracking-wider select-none ${px} text-lime-800 dark:text-[#C6F432] bg-lime-500/15 dark:bg-[rgba(198,244,50,0.12)] border border-lime-600/30 dark:border-[rgba(198,244,50,0.25)] ${className}`}
      aria-label={`${label} content`}
      title="This text was generated by an AI model and is clearly labelled."
    >
      <Sparkles size={size === 'xs' ? 8 : 10} />
      {label}
    </span>
  )
}

/**
 * Block wrapper – wraps AI content with a subtle left border and the badge.
 */
export function AIBlock({ children, className = '' }: AILabelProps) {
  return (
    <div
      className={`rounded-xl p-4 ${className}`}
      style={{
        background: 'rgba(198,244,50,0.04)',
        border: '1px solid rgba(198,244,50,0.18)',
        borderLeft: '3px solid var(--accent)',
      }}
    >
      <div className="flex items-center gap-2 mb-2">
        <AIBadge />
        <span className="text-[10px] text-muted">
          Generated from computed metrics — never alters scores or findings
        </span>
      </div>
      {children}
    </div>
  )
}

/**
 * Fallback block – shown when AI is unavailable or disabled.
 */
export function AIFallback({ message = 'AI unavailable' }: { message?: string }) {
  return (
    <div
      className="rounded-xl p-3 text-xs text-muted italic"
      style={{ background: 'var(--surface)', border: '1px solid var(--surface-border)' }}
      aria-label="AI unavailable"
    >
      <Sparkles size={12} className="inline mr-1.5 opacity-40" />
      {message}
    </div>
  )
}
